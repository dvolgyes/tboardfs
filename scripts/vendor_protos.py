#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12,<3.14"
# dependencies = [
#   "ruff",
#   "tensorboard==2.21.0",
# ]
# ///
"""Vendor TensorBoard's RunMetadata and MetaGraphDef schema as tboardfs/proto/compat_pb2.py.

The module holds every message and enum that RunMetadata and MetaGraphDef
reach in tensorboard/compat/proto, with the same fields, file syntax and
options. Each file moves from tensorboard/compat/proto to
tboardfs/vendored/tensorboard and from package tensorboard to
tboardfs.vendored.tensorboard, so that it does not collide with TensorBoard
or TensorFlow in the default descriptor pool. Types that the two messages do
not reach are left out. The module is formatted with the ruff settings of the
repository.
"""

from pathlib import Path
import subprocess
import sys

from google.protobuf import descriptor_pb2, descriptor_pool
from google.protobuf.descriptor import Descriptor, EnumDescriptor
from tensorboard.compat.proto import config_pb2, meta_graph_pb2

TARGET = Path("tboardfs") / "proto" / "compat_pb2.py"
MODULE = "tboardfs.proto.compat_pb2"
SOURCE_DIR = "tensorboard/compat/proto/"
TARGET_DIR = "tboardfs/vendored/tensorboard/"
SOURCE_PACKAGE, TARGET_PACKAGE = "tensorboard", "tboardfs.vendored.tensorboard"
ROOTS = (config_pb2.RunMetadata.DESCRIPTOR, meta_graph_pb2.MetaGraphDef.DESCRIPTOR)
HEADER = (
    "# Generated by scripts/vendor_protos.py from TensorBoard 2.21.0. DO NOT EDIT!",
    f"# source: {SOURCE_DIR}*.proto, moved to {TARGET_PACKAGE}"
    " (tests/test_proto_namespace.py).",
    "from google.protobuf import any_pb2 as _any_pb2  # noqa: F401",
    "from google.protobuf import descriptor_pool as _descriptor_pool",
    "from google.protobuf import wrappers_pb2 as _wrappers_pb2  # noqa: F401",
    "from google.protobuf.internal import builder as _builder",
    "",
)


def main() -> None:
    """Write the vendored module, replacing an earlier one."""
    types: dict[str, Descriptor | EnumDescriptor] = {}
    for root in ROOTS:
        _Vendor.add_closure(root, types)
    files: dict[str, descriptor_pb2.FileDescriptorProto] = {}
    for descriptor in types.values():
        if descriptor.file.name not in files:
            files[descriptor.file.name] = _Vendor.vendored_file(
                descriptor.file.name, types
            )
    order: list[str] = []
    for name in sorted(files):
        _Vendor.add_in_dependency_order(name, files, order)
    lines = list(HEADER)
    for index, name in enumerate(order):
        serialized = files[name].SerializeToString()
        lines += [
            "",
            f"_FILE_{index} = _descriptor_pool.Default().AddSerializedFile(",
            f"    {serialized!r}",
            ")",
            f"_builder.BuildMessageAndEnumDescriptors(_FILE_{index}, globals())",
            f'_builder.BuildTopDescriptorsAndMessages(_FILE_{index}, "{MODULE}", globals())',
        ]
    TARGET.write_text("\n".join(lines) + "\n")
    # The arguments are constants of this script.
    command = [sys.executable, "-m", "ruff", "format", str(TARGET)]
    subprocess.run(command, check=True)  # noqa: S603


class _Vendor:
    """Copy descriptors of the TensorBoard compat protos into the vendored namespace."""

    @staticmethod
    def add_closure(
        descriptor: Descriptor | EnumDescriptor,
        types: dict[str, Descriptor | EnumDescriptor],
    ) -> None:
        """Add the top-level type of a descriptor and the types it reaches, by full name."""
        top = descriptor
        while top.containing_type is not None:
            top = top.containing_type
        if top.full_name in types or not top.full_name.startswith(f"{SOURCE_PACKAGE}."):
            return
        types[top.full_name] = top
        if not isinstance(top, Descriptor):
            return
        pending = [top]
        while pending:
            message = pending.pop()
            pending.extend(message.nested_types)
            for field in message.fields:
                for referenced in (field.message_type, field.enum_type):
                    if referenced is not None:
                        _Vendor.add_closure(referenced, types)

    @staticmethod
    def vendored_file(
        name: str, types: dict[str, Descriptor | EnumDescriptor]
    ) -> descriptor_pb2.FileDescriptorProto:
        """Return one file with the reached types, in the vendored namespace."""
        original = descriptor_pb2.FileDescriptorProto()
        descriptor_pool.Default().FindFileByName(name).CopyToProto(original)
        if original.service or original.extension:
            msg = f"{name} has services or extensions"
            raise ValueError(msg)
        kept = {full_name.rsplit(".", 1)[1] for full_name in types}
        vendored = descriptor_pb2.FileDescriptorProto()
        vendored.CopyFrom(original)
        vendored.name = TARGET_DIR + name.removeprefix(SOURCE_DIR)
        vendored.package = TARGET_PACKAGE
        del vendored.message_type[:]
        del vendored.enum_type[:]
        vendored.message_type.extend(m for m in original.message_type if m.name in kept)
        vendored.enum_type.extend(e for e in original.enum_type if e.name in kept)
        referenced: set[str] = set()
        pending = list(vendored.message_type)
        while pending:
            message = pending.pop()
            pending.extend(message.nested_type)
            for field in message.field:
                if field.type_name.startswith(f".{SOURCE_PACKAGE}."):
                    full_name = field.type_name[1:]
                    local_name = full_name.removeprefix(f"{SOURCE_PACKAGE}.")
                    field.type_name = f".{TARGET_PACKAGE}.{local_name}"
                    top = ".".join(full_name.split(".")[:2])
                    referenced.add(types[top].file.name)
                elif field.type_name:
                    pool = descriptor_pool.Default()
                    referenced.add(
                        pool.FindMessageTypeByName(field.type_name[1:]).file.name
                    )
        referenced.discard(name)
        del vendored.dependency[:]
        del vendored.public_dependency[:]
        del vendored.weak_dependency[:]
        vendored.dependency.extend(
            TARGET_DIR + dependency.removeprefix(SOURCE_DIR)
            if dependency.startswith(SOURCE_DIR)
            else dependency
            for dependency in sorted(referenced)
        )
        vendored.ClearField("source_code_info")
        return vendored

    @staticmethod
    def add_in_dependency_order(
        name: str,
        files: dict[str, descriptor_pb2.FileDescriptorProto],
        order: list[str],
    ) -> None:
        """Append a source file name to order after the files it depends on."""
        if name in order:
            return
        for dependency in files[name].dependency:
            source = SOURCE_DIR + dependency.removeprefix(TARGET_DIR)
            if source in files:
                _Vendor.add_in_dependency_order(source, files, order)
        order.append(name)


if __name__ == "__main__":
    main()
